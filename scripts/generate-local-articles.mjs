import "dotenv/config";
import fs from "fs/promises";
import path from "path";
import { fileURLToPath } from "url";
import { createClient } from "@supabase/supabase-js";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const rootDir = path.resolve(__dirname, "..");
const outputPath = path.join(rootDir, "shared", "localArticles.generated.ts");

const supabaseUrl = process.env.SUPABASE_URL;
const supabaseKey = process.env.SUPABASE_SERVICE_KEY;

if (!supabaseUrl || !supabaseKey) {
  console.error("Missing SUPABASE_URL or SUPABASE_SERVICE_KEY.");
  process.exit(1);
}

const supabase = createClient(supabaseUrl, supabaseKey);

const parseContent = (value) => {
  if (!value) return [];
  if (Array.isArray(value)) return value;
  if (typeof value === "string") {
    try {
      return JSON.parse(value);
    } catch {
      return [{ type: "html", content: value }];
    }
  }
  return [];
};

const normalizeArticle = (article) => ({
  id: article.id,
  slug: article.slug,
  title: article.title,
  excerpt: article.excerpt || "",
  coverImageUrl: article.cover_image || "",
  coverImageAlt: article.title,
  publishedAt: article.published_at,
  updatedAt: article.updated_at || article.published_at,
  createdAt: article.created_at || article.published_at,
  categoryName: article.categories?.name || "Article",
  seoTitle: article.seo_title || article.title,
  seoDescription: article.seo_description || article.excerpt || "",
  seoKeywords: article.seo_keywords || null,
  featured: Boolean(article.featured),
  readTime: article.read_time || null,
  tags: (article.article_tags || [])
    .map((entry) => entry.tags)
    .filter(Boolean)
    .map((tag) => ({
      id: tag.id,
      name: tag.name,
      slug: tag.slug,
    })),
  content: parseContent(article.content),
});

const { data, error } = await supabase
  .from("articles")
  .select(
    "id,title,slug,excerpt,content,cover_image,read_time,status,featured,seo_title,seo_description,seo_keywords,created_at,updated_at,published_at,categories(name,slug),article_tags(tag_id,tags(id,name,slug))"
  )
  .eq("status", "published")
  .order("published_at", { ascending: false });

if (error) {
  console.error(error);
  process.exit(1);
}

const generatedLocalArticles = (data || []).map(normalizeArticle);

const fileContents = `// Auto-generated by scripts/generate-local-articles.mjs
// Do not edit manually. Re-run the generator after article DB changes.

export const generatedLocalArticles = ${JSON.stringify(generatedLocalArticles, null, 2)};\n`;

await fs.writeFile(outputPath, fileContents, "utf8");

console.log(`Generated ${generatedLocalArticles.length} local articles at ${outputPath}`);
